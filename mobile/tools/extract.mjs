// Pulls the power-up and game-pack definitions out of the PC app's panel.html, so the phone app
// always offers the same things as Clutch for PC. Then works out which ones a console box can run
// (no keyboard, mouse, crosshair overlay, gyro or PC-only buttons) and writes www/js/catalog.gen.js.
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const panel = fs.readFileSync(path.join(here, "..", "..", "panel.html"), "utf8");
const script = panel.slice(panel.indexOf("<script>") + 8, panel.lastIndexOf("</script>"));
const lines = script.split("\n");

function between(startRe, endRe, label){
  const a = lines.findIndex(l => startRe.test(l));
  if (a < 0) throw new Error("extract: start not found for " + label);
  const b = lines.findIndex((l, i) => i >= a && endRe.test(l));
  if (b < 0) throw new Error("extract: end not found for " + label);
  return lines.slice(a, b + 1).join("\n");
}
function fn(name){  // a top-level function or one-line const
  const i = lines.findIndex(l => l.startsWith(`function ${name}(`) || l.startsWith(`const ${name} = `));
  if (i < 0) throw new Error("extract: missing " + name);
  if (lines[i].startsWith("const ") || lines[i].trimEnd().endsWith("}")) return lines[i];
  const j = lines.findIndex((l, k) => k > i && l === "}");
  return lines.slice(i, j + 1).join("\n");
}

const parts = [
  "/* ---- names (from panel.html) */",
  between(/^const NAMES = \{/, /^const XBOX = /, "names"),
  "/* ---- helpers (from panel.html) */",
  ...["clone", "isObj", "merge", "getPath", "same", "num", "clamp", "listify", "pct", "times", "pow", "setIn", "delIn",
      "resolve", "parentOf", "defaultTarget"].map(fn),
  "/* ---- power-ups (from panel.html) */",
  between(/^\/\* =+ POWER-UPS \*\//, /^function applyPU\(/, "power-ups"),
  fn("applyPU").split("\n").slice(1).join("\n"),
  "/* ---- game packs (from panel.html) */",
  between(/^const KBM = \(\) =>/, /^const PACK_CATS = /, "packs"),
];
let code = parts.join("\n");

// ---- work out what a console box can run: apply each power-up / pack to an empty profile and look at it
const PC_ONLY = /"(key|mouse):|"output":"mouse"|"crosshair|"gyro"|"overlay|"media_|"clip"|"screenshot"/;
const sandbox = { console, CFG: { profiles: { Test: {} } }, STATE: null, curProfile: "Test", puProfile: "Test",
  h: () => null, outName: b => b, curKid: () => null, toast() {}, changed() {}, go() {}, renderAll() {} };
vm.createContext(sandbox);
vm.runInContext(code + "\n;this.__POWERUPS = POWERUPS; this.__PACKS = PACKS; this.__COMBOS = COMBOS; this.__applyPU = applyPU;", sandbox);
const consoleOk = {}, packOk = {};
for (const pu of sandbox.__POWERUPS){
  sandbox.CFG.profiles = { Test: {} };
  let ok = pu.cat !== "PC and media" && !pu.global;
  try { sandbox.__applyPU(pu); } catch (e){ ok = false; }
  if (PC_ONLY.test(JSON.stringify(sandbox.CFG.profiles.Test))) ok = false;
  consoleOk[pu.id] = ok;
}
for (const pk of sandbox.__PACKS){
  let ok = pk.cat !== "Keyboard games";
  try { if (PC_ONLY.test(JSON.stringify(pk.make()))) ok = false; } catch (e){ ok = false; }
  packOk[pk.id] = ok;
}
const onPU = Object.keys(consoleOk).filter(k => consoleOk[k]), onPK = Object.keys(packOk).filter(k => packOk[k]);
code += `
/* ---- generated: what the console box can run */
const CONSOLE_PU = new Set(${JSON.stringify(onPU)});
const CONSOLE_PACKS = new Set(${JSON.stringify(onPK)});
`;
const out = path.join(here, "..", "www", "js", "catalog.gen.js");
fs.writeFileSync(out, "// GENERATED by tools/extract.mjs from ../panel.html. Don't edit by hand.\n" + code);
console.log(`catalog: ${onPU.length}/${sandbox.__POWERUPS.length} power-ups and ${onPK.length}/${sandbox.__PACKS.length} packs work on the box`);
console.log("left out:", Object.keys(consoleOk).filter(k => !consoleOk[k]).join(", "));
console.log("packs left out:", Object.keys(packOk).filter(k => !packOk[k]).join(", "));
